/**
 * 日本の和暦変換および祝日判定ユーティリティ
 * 祝日は内閣府の確定値テーブルで管理
 */

// 和暦（元号）の定義
interface Era {
    name: string;
    startYear: number;
    startMonth: number;
    startDate: number;
}

const ERAS: Era[] = [
    { name: '令和', startYear: 2019, startMonth: 5, startDate: 1 },
    { name: '平成', startYear: 1989, startMonth: 1, startDate: 8 },
    { name: '昭和', startYear: 1926, startMonth: 12, startDate: 25 }
];

/**
 * 西暦から和暦への変換
 */
export function getJapaneseEra(year: number, month: number = 1, date: number = 1): string {
    const targetDate = new Date(year, month - 1, date);
    for (const era of ERAS) {
        const eraStartDate = new Date(era.startYear, era.startMonth - 1, era.startDate);
        if (targetDate >= eraStartDate) {
            const eraYear = year - era.startYear + 1;
            const eraYearStr = eraYear === 1 ? '元' : String(eraYear);
            return `${era.name}${eraYearStr}年`;
        }
    }
    return `西暦${year}年`;
}

